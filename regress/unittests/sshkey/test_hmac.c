void
sshkey_hmac_tests(void)
{
	struct ssh_hmac_ctx *ctx;
	const struct hmac_test *tst;
	const struct hmac_test_vector *vec;
	size_t i, j;
	unsigned char digest[SSH_DIGEST_MAX_LENGTH];

	TEST_START("hmac");
	for (i = 0; hmac_tests[i].alg != -1; ++i) {
		tst = &hmac_tests[i];
		for (j = 0; tst->vecs[j].data != NULL; ++j) {
			vec = &tst->vecs[j];
			ctx = ssh_hmac_start(tst->alg);
			ASSERT_PTR_NE(ctx, NULL);
			ASSERT_INT_EQ(ssh_hmac_init(ctx, vec->key, vec->keylen), 0);
			ASSERT_INT_EQ(ssh_hmac_update(ctx, vec->data, vec->datalen), 0);
			ASSERT_INT_EQ(ssh_hmac_final(ctx, digest, sizeof digest), 0);
			ASSERT_MEM_EQ(digest, vec->digest, vec->digestlen);
			ssh_hmac_free(ctx);
		}
	}
	TEST_DONE();
}
