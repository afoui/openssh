void
sshkey_umac_tests(void)
{
#ifdef ENABLE_NONFIPS
	size_t i, j;
	const struct umac_test_vector *vec;
	struct umac_ctx *ctx64 = NULL, *ctx128 = NULL;
	u_char tag64[UMAC64_TAG_LEN], tag128[UMAC128_TAG_LEN];
	const u_char *data;
	size_t datalen;

	TEST_START("umac");

	for (i = 0; ; ++i) {
		vec = &umac_vecs[i];
		if (vec->word == NULL)
			break;

		data = (const unsigned char *)vec->word;
		datalen = strlen(data);

		ctx64 = umac_new((const u_char *)umac_key);
		ASSERT_PTR_NE(ctx64, NULL);
		for (j = 0; j < vec->nrepeats; ++j)
			ASSERT_INT_EQ(umac_update(ctx64, data, datalen), 1);
		ASSERT_INT_EQ(umac_final(ctx64, tag64, (const u_char *)umac_nonce), 1);
		ASSERT_INT_EQ(umac_delete(ctx64), 1);
		ASSERT_MEM_EQ(tag64, vec->tag64, sizeof tag64);

		ctx128 = umac128_new((const u_char *)umac_key);
		ASSERT_PTR_NE(ctx128, NULL);
		for (j = 0; j < vec->nrepeats; ++j)
			ASSERT_INT_EQ(umac128_update(ctx128, data, datalen), 1);
		ASSERT_INT_EQ(umac128_final(ctx128, tag128, (const u_char *)umac_nonce), 1);
		ASSERT_INT_EQ(umac128_delete(ctx128), 1);
		ASSERT_MEM_EQ(tag128, vec->tag128, sizeof tag128);
	}

	TEST_DONE();
#endif /* ENABLE_NONFIPS */
}
