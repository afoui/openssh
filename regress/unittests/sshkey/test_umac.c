/* From umac.c */
#define UMAC_KEY_LEN           16  /* UMAC takes 16 bytes of external key */

#define UMAC64_TAG_LEN 8 /* 64 bits = 8 bytes*/
#define UMAC128_TAG_LEN 16 /* 128 bits = 16 bytes */

/* Sized array, string */
#define SZARR(arr) (arr), sizeof(arr)
#define SZSTR(s) ((const unsigned char *)(s)), (sizeof(s) - 1)

void sshkey_umac_tests(void);

struct umac_test_vector
{
	const char *word; /* message element */
	unsigned long nrepeats; /* number of times the message element is repeated */
	unsigned char tag64[UMAC64_TAG_LEN];
	unsigned char tag128[UMAC128_TAG_LEN];
};

